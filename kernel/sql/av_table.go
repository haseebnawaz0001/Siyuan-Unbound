package sql

import (
	"fmt"

	"github.com/88250/lute/ast"
	"github.com/siyuan-note/siyuan/kernel/av"
	"github.com/siyuan-note/siyuan/kernel/util"
)

func RenderAttributeViewTable(attrView *av.AttributeView, view *av.View, query string, depth *int, cachedAttrViews map[string]*av.AttributeView, ignoreRows bool) (ret *av.Table) {
	viewable := attrView.RenderedViewables[view.ID]
	if nil != viewable {
		ret = viewable.(*av.Table)
		return
	}

	ret = &av.Table{
		BaseInstance: av.NewViewBaseInstance(view),
		Columns:      []*av.TableColumn{},
		Rows:         []*av.TableRow{},
	}

	// Assemble the columns
	for _, col := range view.Table.Columns {
		key, getErr := attrView.GetKey(col.ID)
		if nil != getErr {
			// If the field can't be found, remove it from the view (a metadata-query scenario doesn't persist to disk)
			if !ignoreRows {
				removeMissingField(attrView, view, col.ID)
			}
			continue
		}

		ret.Columns = append(ret.Columns, &av.TableColumn{
			BaseInstanceField: &av.BaseInstanceField{
				ID:           key.ID,
				Name:         key.Name,
				Type:         key.Type,
				Icon:         key.Icon,
				Wrap:         col.Wrap,
				Hidden:       col.Hidden,
				Desc:         key.Desc,
				Calc:         col.Calc,
				Options:      key.Options,
				NumberFormat: key.NumberFormat,
				Template:     key.Template,
				Relation:     key.Relation,
				Rollup:       key.Rollup,
				Date:         key.Date,
				Created:      key.Created,
				Updated:      key.Updated,
			},
			Width: col.Width,
			Pin:   col.Pin,
			Align: col.Align,
		})
	}

	// For scenarios like menus that only need field/view metadata, skip processing every row
	if ignoreRows {
		return
	}

	rowsValues := generateAttrViewItems(attrView, view) // Generate rows
	filterNotFoundAttrViewItems(rowsValues)             // Filter out rows that no longer exist

	// Generate the row cells
	for rowID, rowValues := range rowsValues {
		// Index by field ID, to avoid a linear lookup per cell in the column loop below
		kvByCol := map[string]*av.KeyValues{}
		for _, keyValues := range rowValues {
			if _, ok := kvByCol[keyValues.Key.ID]; !ok { // When the same field has multiple values, only take the first
				kvByCol[keyValues.Key.ID] = keyValues
			}
		}

		var tableRow av.TableRow
		for _, col := range ret.Columns {
			var tableCell *av.TableCell
			if keyValues, ok := kvByCol[col.ID]; ok {
				tableCell = &av.TableCell{
					BaseValue: &av.BaseValue{
						ID:        keyValues.Values[0].ID,
						Value:     keyValues.Values[0],
						ValueType: col.Type,
					},
				}
			}
			if nil == tableCell {
				tableCell = &av.TableCell{
					BaseValue: &av.BaseValue{
						ID:        rowID[:14] + ast.NewNodeID()[14:],
						ValueType: col.Type,
					},
				}
			}
			tableRow.ID = rowID

			filedDateIsTime := false
			if nil != col.Date {
				filedDateIsTime = col.Date.FillSpecificTime
			}
			fillAttributeViewBaseValue(tableCell.BaseValue, col.ID, rowID, col.NumberFormat, col.Template, filedDateIsTime)
			tableRow.Cells = append(tableRow.Cells, tableCell)
		}
		ret.Rows = append(ret.Rows, &tableRow)
	}

	// Backfill and complete the data
	fillAttributeViewKeyValues(attrView, ret)

	// Batch-fetch block attributes to improve performance
	var ialIDs []string
	for _, row := range ret.Rows {
		blockVal := row.GetBlockValue()
		if nil != blockVal && !blockVal.IsDetached {
			ialIDs = append(ialIDs, blockVal.Block.ID)
		}
	}
	ials := BatchGetBlockAttrs(ialIDs)

	// Render auto-generated field values, such as relation, rollup, created time, and updated time
	fillAttributeViewAutoGeneratedValues(attrView, ret, ials, depth, cachedAttrViews)

	// Render template fields last, so templates can use the rollup, relation, created time, and updated time values
	renderTemplateErr := fillAttributeViewTemplateValues(attrView, view, ret, ials)
	if nil != renderTemplateErr {
		util.PushErrMsg(fmt.Sprintf(util.Langs[util.Lang][44], util.EscapeHTML(renderTemplateErr.Error())), 30000)
	}

	filterByQuery(query, ret)
	manualSort(view, ret)
	return
}
